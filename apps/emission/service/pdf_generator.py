def _display_financial_year(financial_year):
    if not financial_year:
        return "FY 2024-25"
    value = str(financial_year).strip()
    if value.upper().startswith("FY "):
        value = value[3:].strip()
    parts = value.split("-")
    if len(parts) == 2 and len(parts[0]) == 4 and len(parts[1]) == 4:
        value = f"{parts[0]}-{parts[1][-2:]}"
    return f"FY {value}"


def _short_company_name(company_name):
    value = (company_name or "Lucas TVS").strip()
    for suffix in (" Private Limited", " Limited", " Pvt. Ltd.", " Pvt Ltd", " Ltd.", " Ltd"):
        if value.lower().endswith(suffix.lower()):
            return value[: -len(suffix)].strip()
    return value


def _fit_font_size(text, font_name, max_size, max_width, min_size=9):
    """Largest font size (<= max_size) at which `text` fits in max_width."""
    size = max_size
    while size > min_size and stringWidth(text, font_name, size) > max_width:
        size -= 0.5
    return size


def _draw_sidebar(canvas):
    """Full-height green Lucas TVS / ESG strip on the left (every page)."""
    canvas.drawImage(
        _image("sidebar", _SIDEBAR_PNG_B64),
        _SIDEBAR_X_FRAC * PAGE_W,
        0,
        width=_SIDEBAR_W_FRAC * PAGE_W,
        height=PAGE_H,
        mask="auto",
    )


def _draw_logo(canvas):
    """Lucas TVS logo, top centre (cover only)."""
    h = _LOGO_H_FRAC * PAGE_H
    canvas.drawImage(
        _image("logo", _LOGO_PNG_B64),
        _LOGO_X_FRAC * PAGE_W,
        PAGE_H - _LOGO_Y_FRAC * PAGE_H - h,
        width=_LOGO_W_FRAC * PAGE_W,
        height=h,
        mask="auto",
    )


class BRSRPDFGenerator:
    """Generate a BRSR-styled PDF report with emission data only."""

    def __init__(
        self,
        assignment_id: Optional[int] = None,
        company_id: Optional[int] = None,
        plant_id: Optional[int] = None,
        financial_year_id: Optional[int] = None,
        financial_month_id: Optional[int] = None,
        company_name: str = None,
        cin: str = None,
        report_year: str = None,
        user=None,
    ):
        self.assignment_id      = assignment_id
        self.company_id         = company_id
        self.plant_id           = plant_id
        self.financial_year_id  = financial_year_id
        self.financial_month_id = financial_month_id
        self.user               = user
        self._report_data       = {}

        if company_name:
            self.company_name = company_name
            self.cin          = cin or self._get_cin_only_from_user()
        else:
            self.company_name, self.cin = self._get_company_details_from_user()

        if not self.cin:
            self.cin = "N/A"

        if report_year is None:
            from apps.organizations.models import FinancialYear
            today = timezone.now().date()
            current_fy = FinancialYear.objects.filter(
                start_date__lte=today, end_date__gte=today
            ).first()
            self.report_year = current_fy.financial_year if current_fy else "2024-25"
        else:
            self.report_year = report_year

        self.buffer = BytesIO()
        self._build_styles()

    # ----------------------------------------------------------------------
    # Company detail lookup
    # ----------------------------------------------------------------------
    def _get_company_details_from_user(self) -> Tuple[str, str]:
        from apps.accounts.models import User
        from apps.companies.models import Company

        default_name, default_cin = "Lucas TVS Ltd", "N/A"
        if not self.user:
            return default_name, default_cin

        try:
            if hasattr(self.user, 'company') and self.user.company:
                c = self.user.company
                return c.company_name, getattr(c, 'cin_number', None) or default_cin  # ✅ FIXED

            if hasattr(self.user, 'company_id') and self.user.company_id:
                try:
                    c = Company.objects.get(id=self.user.company_id)
                    return c.company_name, getattr(c, 'cin_number', None) or default_cin  # ✅ FIXED
                except Company.DoesNotExist:
                    pass

            uid = getattr(self.user, 'id', None)
            if uid:
                try:
                    u = User.objects.select_related('company').get(id=uid)
                    if u.company:
                        return u.company.company_name, getattr(u.company, 'cin_number', None) or default_cin  # ✅ FIXED
                except User.DoesNotExist:
                    pass
        except Exception:
            pass

        return default_name, default_cin

    def _get_cin_only_from_user(self) -> str:
        _, cin = self._get_company_details_from_user()
        return cin

    # ----------------------------------------------------------------------
    # Public API
    # ----------------------------------------------------------------------
    def generate(self) -> BytesIO:
        doc = SimpleDocTemplate(
            self.buffer,
            pagesize=A4,
            leftMargin=LEFT_MARGIN,
            rightMargin=RIGHT_MARGIN,
            topMargin=TOP_MARGIN,
            bottomMargin=BOTTOM_MARGIN,
            title=f"Emissions Report - {self.company_name}",
        )

        data = self._get_report_data()
        self._report_data = data

        story = []
        story.append(Spacer(1, 1))          # cover is drawn on the canvas
        story.append(PageBreak())

        if INCLUDE_BRSR_OVERVIEW:
            story.extend(self._get_overview_page())
            story.append(PageBreak())

        story.extend(self._get_scope_summary_page(data))
        story.append(PageBreak())

        story.extend(self._get_scope_breakdown(data))

        doc.build(
            story,
            onFirstPage=self._draw_cover_page,
            onLaterPages=self._draw_later_page,
        )

        self.buffer.seek(0)
        return self.buffer

