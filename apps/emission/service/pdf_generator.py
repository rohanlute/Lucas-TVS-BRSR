    def _get_scope_breakdown(self, data: Dict) -> List:
        elements = []
        if not data['scopes']:
            s = ParagraphStyle('NoData', fontName="Helvetica", fontSize=10,
                               textColor=MUTED_TEXT, alignment=TA_CENTER,
                               spaceAfter=20)
