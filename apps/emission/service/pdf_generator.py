def download_emission_pdf(request, assignment_id=None):
    from django.http import JsonResponse
    from apps.accounts.models import User
    from apps.companies.models import Company

    try:
        assignment = EmissionAssignment.objects.get(id=assignment_id)
        user = request.user
        company_name = None
        cin = None

        if user.is_authenticated:
            user = User.objects.select_related('company').get(id=user.id)
            if user.company:
                company_name = user.company.company_name
                cin = getattr(user.company, 'cin_number', None)  # ✅ FIXED

        if not company_name and assignment.company_id:
            try:
                c = Company.objects.get(id=assignment.company_id)
                company_name = c.company_name
                cin = getattr(c, 'cin_number', None)  # ✅ FIXED
            except Company.DoesNotExist:
                pass

        if not company_name: company_name = "Lucas TVS Ltd"
        if not cin:          cin = "N/A"

        has_access = (
            assignment.assignee == user
            or assignment.assigner == user
            or assignment.reviewer == user
            or (hasattr(user, 'role') and user.role and
                user.role.role_code in ['COMPANYADMIN', 'ESG-HEAD', 'ESG-COORD'])
        )
        if not has_access:
            return JsonResponse(
                {'success': False,
                 'message': 'You do not have permission to download this report.'},
                status=403)

        pdf_buffer = generate_emission_pdf_report(
            assignment_id=assignment_id,
            company_id=assignment.company_id,
            plant_id=assignment.plant_id,
            financial_year_id=assignment.financial_year_id,
            financial_month_id=assignment.financial_month_id,
            company_name=company_name,
            cin=cin,
            user=user,
        )

        timestamp = timezone.now().strftime('%Y%m%d_%H%M%S')
        filename = f"Emissions_Report_{assignment.assignment_code}_{timestamp}.pdf"

        response = HttpResponse(pdf_buffer.getvalue(),
                                content_type='application/pdf')
        response['Content-Disposition'] = f'attachment; filename="{filename}"'
        return response

    except EmissionAssignment.DoesNotExist:
        return JsonResponse({'success': False, 'message': 'Assignment not found.'},
                            status=404)
    except Exception as e:
        import traceback
        traceback.print_exc()
        return JsonResponse(
            {'success': False, 'message': f'Error generating PDF: {str(e)}'},
            status=500)