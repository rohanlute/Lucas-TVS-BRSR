        k = TABLE_WIDTH / sum(base)
        col_widths = [b * k for b in base]

        usable_space = 620

        for idx, scope in enumerate(data['scopes']):
            if idx > 0:
                elements.append(PageBreak())
            current = 0

            header_elems = [
                self._heading("Scope-wise Emission Breakdown"),
                Paragraph(f"{self._esc(scope['code'])} — {self._esc(scope['name'])}",
                          self.st['sub']),
            ]
            if scope.get('description'):
                header_elems.append(
                    Paragraph(self._esc(self._clean_text(scope['description'])),
                              self.st['scope_desc']))

            for elem in header_elems:
                elements.append(elem)
                current += 25

            for category in scope['categories']:
                adata = [['Activity', 'Source', 'Quantity', 'Unit',
                          'Total (kgCO2e)', 'Total (tCO2e)']]
                spans = []
                t_qty = t_kg = t_t = Decimal('0')
                row_count = 1

                for activity in category['activities']:
                    t_qty += activity['total_quantity'] or Decimal('0')
                    t_kg  += activity.get('total_emission_kg') or Decimal('0')
                    t_t   += activity['total_emission'] or Decimal('0')

                    if activity['sources']:
                        first = True
                        start = len(adata)
                        for source in activity['sources']:
                            adata.append([
                                activity['name'] if first else '',
                                source.get('name', 'Unknown'),
                                f"{source.get('quantity', 0):,.2f}",
                                source.get('unit', ''),
                                f"{source.get('emission_kg', 0):,.2f}",
                                f"{source.get('emission', 0):,.2f}",
                            ])
                            first = False
                            row_count += 1
                        if len(activity['sources']) > 1:
                            spans.append(('SPAN', (0, start),
                                          (0, start + len(activity['sources']) - 1)))
                    else:
                        adata.append([activity['name'], 'No sources available',
                                      '0.00', '', '0.00', '0.00'])
                        row_count += 1

                adata.append(['Category Total', '',
                              f"{t_qty:,.2f}", '',
                              f"{t_kg:,.2f}", f"{t_t:,.2f}"])
                row_count += 1

                table_height = row_count * 18 + 25
                needed = 25 + table_height + 12

                if current + needed > usable_space:
                    elements.append(PageBreak())
                    for elem in header_elems:
                        elements.append(elem)
                    current = len(header_elems) * 25

                elements.append(self._category_heading(category['name']))
                current += 25

                elements.append(self._brsr_table(
                    adata, col_widths, header_rows=1, spans=spans))
                current += table_height

                elements.append(Spacer(1, 0.06 * inch))
                current += 12

            if scope['total'] > 0:
                st = ParagraphStyle(
                    'ScopeTotal', fontName="Helvetica-Bold", fontSize=11,
                    alignment=TA_RIGHT, textColor=BRAND, spaceAfter=4)
                elements.append(Paragraph(
                    f"Scope {self._esc(scope['code'])} Total: "
                    f"{scope['total']:,.2f} tCO2e", st))
                current += 30

            elements.append(HRFlowable(
                width="100%", thickness=1, color=GOLD_BORDER,
                spaceBefore=4, spaceAfter=8))

        if data['total_emissions'] > 0:
            gt = ParagraphStyle(
                'GrandTotal', fontName="Helvetica-Bold", fontSize=14,
                alignment=TA_RIGHT, textColor=BRAND,
                spaceBefore=6, spaceAfter=10)
            elements.append(Paragraph(
                f"GRAND TOTAL: {data['total_emissions']:,.2f} tCO2e", gt))

        return elements


