    def _clean_text(self, text: str) -> str:
        if not text:
            return text
        replacements = {
            '₆': '6', '₄': '4', '₂': '2', '₃': '3', '₁': '1', '₅': '5',
            '₇': '7', '₈': '8', '₉': '9', '₀': '0',
            '■': '', '●': '', '•': '',
            '—': '-', '–': '-', '…': '...',
            '”': '"', '“': '"', '’': "'", '‘': "'",
        }
        for old, new in replacements.items():
            text = text.replace(old, new)
        return text

    def _get_report_data(self) -> Dict:
        filter_kwargs = {}
        if self.assignment_id:      filter_kwargs['assignment_id']      = self.assignment_id
        if self.company_id:         filter_kwargs['company_id']         = self.company_id
        if self.plant_id:           filter_kwargs['plant_id']           = self.plant_id
        if self.financial_year_id:  filter_kwargs['financial_year_id']  = self.financial_year_id
        if self.financial_month_id: filter_kwargs['financial_month_id'] = self.financial_month_id

        plant_name = "All Plants"
        plant_names: List[str] = []     # used on the cover for consolidated reports
        from apps.organizations.models import Plant
        
        if self.plant_id:
            # Single plant selected
            try:
                plant = Plant.objects.get(id=self.plant_id)
                plant_name = plant.name
            except Plant.DoesNotExist:
                pass
        else:
            # "All Plants" selected - fetch ALL active plants belonging to this company
            try:
                plant_qs = Plant.objects.filter(is_active=True)
                
                # Filter plants by company (if the Plant model has a company FK)
                if self.company_id:
                    # Try common field names for the company relation on Plant
                    if hasattr(Plant, 'company_id'):
                        plant_qs = plant_qs.filter(company_id=self.company_id)
                    elif hasattr(Plant, 'company'):
                        plant_qs = plant_qs.filter(company__id=self.company_id)
                
                # Try to also filter by assignment's company if assignment_id is given
                if self.assignment_id:
                    try:
                        assignment = EmissionAssignment.objects.get(id=self.assignment_id)
                        if assignment.company_id:
                            if hasattr(Plant, 'company_id'):
                                plant_qs = plant_qs.filter(company_id=assignment.company_id)
                            elif hasattr(Plant, 'company'):
                                plant_qs = plant_qs.filter(company__id=assignment.company_id)
                    except EmissionAssignment.DoesNotExist:
                        pass
                
                plant_names = list(
                    plant_qs.order_by('name').values_list('name', flat=True)
                )
            except Exception as e:
                print(f"Error fetching plant names: {e}")
                plant_names = []
        
        # Debug: print what we found
        print(f"[PDF] plant_id={self.plant_id}, plant_name={plant_name}, plants={plant_names}")

        scopes_data = []
        scopes = EmissionScope.objects.filter(is_active=True).order_by('display_order')
        total_emissions = Decimal('0')
        scope_totals = {}

        for scope in scopes:
            scope_data = {
                'id': scope.id, 'code': scope.code, 'name': scope.name,
                'description': scope.description,
                'categories': [], 'total': Decimal('0'),
            }

            categories = EmissionCategory.objects.filter(
                scope=scope, is_active=True
            ).order_by('display_order')

            for category in categories:
                category_data = {
                    'id': category.id, 'name': category.name,
                    'description': category.description,
                    'activities': [], 'total': Decimal('0'),
                }

                activities = EmissionActivity.objects.filter(
                    category=category, is_active=True
                ).order_by('display_order')

                for activity in activities:
                    all_sources = EmissionSource.objects.filter(
                        activity=activity, is_active=True
                    ).order_by('display_order')

                    transactions = EmissionTransaction.objects.filter(
                        activity_id=activity.id, **filter_kwargs
                    ).select_related('source', 'unit')

                    has_data = transactions.exists()
                    total_quantity        = Decimal('0')
                    total_emission_kg     = Decimal('0')
                    total_emission_tco2e  = Decimal('0')

                    if has_data:
                        total_quantity = transactions.aggregate(
                            total=Sum('quantity'))['total'] or Decimal('0')
                        total_emission_kg = transactions.aggregate(
                            total=Sum('total_emission'))['total'] or Decimal('0')
                        total_emission_tco2e = total_emission_kg / Decimal('1000')

                    sources = []
                    if all_sources.exists():
                        for source in all_sources:
                            stx = transactions.filter(source=source)
                            if stx.exists():
                                s_qty = stx.aggregate(total=Sum('quantity'))['total'] or Decimal('0')
                                s_kg  = stx.aggregate(total=Sum('total_emission'))['total'] or Decimal('0')
                                s_t   = s_kg / Decimal('1000')
                                first = stx.first()
                                unit  = first.unit.symbol if first and first.unit else ''
                            else:
                                s_qty = s_kg = s_t = Decimal('0')
                                unit  = activity.base_unit.symbol if activity.base_unit else ''
                            sources.append({
                                'name':        self._clean_text(source.source_name),
                                'unit':        unit,
                                'quantity':    s_qty,
                                'emission_kg': s_kg,
                                'emission':    s_t,
                                'has_data':    stx.exists(),
                            })
                    else:
                        if has_data:
                            groups = transactions.values(
                                'source__source_name', 'unit__symbol'
                            ).annotate(
                                total_qty=Sum('quantity'),
                                total_em=Sum('total_emission')
                            ).order_by('source__display_order')
                            for sg in groups:
                                kg = sg.get('total_em', 0) or Decimal('0')
                                sources.append({
                                    'name':        self._clean_text(sg.get('source__source_name', 'Unknown')),
                                    'unit':        sg.get('unit__symbol', ''),
                                    'quantity':    sg.get('total_qty', 0),
                                    'emission_kg': kg,
                                    'emission':    kg / Decimal('1000'),
                                    'has_data':    True,
                                })
                        else:
                            unit = activity.base_unit.symbol if activity.base_unit else ''
                            sources.append({
                                'name': 'No data available', 'unit': unit,
                                'quantity': Decimal('0'),
                                'emission_kg': Decimal('0'),
                                'emission': Decimal('0'),
                                'has_data': False,
                            })

                    activity_data = {
                        'id': activity.id,
                        'name': self._clean_text(activity.name),
                        'code': activity.code,
                        'total_quantity':       total_quantity,
                        'total_emission_kg':    total_emission_kg,
                        'total_emission':       total_emission_tco2e,
                        'has_data': has_data,
                        'sources': sources,
                    }
                    category_data['activities'].append(activity_data)
                    category_data['total'] += total_emission_tco2e

                if category_data['activities']:
                    scope_data['categories'].append(category_data)
                    scope_data['total'] += category_data['total']
                    total_emissions += category_data['total']

            if scope_data['categories']:
                scopes_data.append(scope_data)
                scope_totals[scope.code] = scope_data['total']

        return {
            'scopes':              scopes_data,
            'total_emissions':     total_emissions,
            'scope_totals':        scope_totals,
            'plant_name':          plant_name,
            'plant_names':         plant_names,
            'consolidated_plants': plant_names if not self.plant_id else [],
            'company_name':        self.company_name,
            'cin':                 self.cin,
            'generated_date':      timezone.now().strftime('%d-%b-%Y %H:%M'),
            'report_year':         self.report_year,
            'has_data':            len(scopes_data) > 0,
        }

